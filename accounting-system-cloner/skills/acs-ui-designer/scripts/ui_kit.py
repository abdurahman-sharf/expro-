#!/usr/bin/env python3
"""ui_kit.py - helpers for acs-ui-designer (standard library only).

  init      Create <spec>/ui/ (screens/, print/, archetypes/, kit/) and copy the prototype kit.
  tokens    Validate ui/tokens.json and generate ui/kit/tokens.css (light, dark, data-theme overrides).
  lint      Static checks on every prototype: RTL, kit links, labels, no literal colours, no external hosts.
  index     Build ui/index.html: design system, archetypes, every screen grouped by ui/navigation.json,
            print templates and the coverage summary from ui/coverage.md.

Run with --project <path-to-spec-folder>.
"""

from __future__ import annotations

import argparse
import html
import json
import re
import shutil
import sys
from pathlib import Path

KIT = Path(__file__).resolve().parent.parent / "assets" / "kit"
REQUIRED_COLORS = ["bg", "surface", "surface-2", "border", "text", "text-muted", "primary", "primary-hover",
                   "primary-soft", "on-primary", "focus", "success", "success-bg", "warning", "warning-bg",
                   "danger", "danger-bg", "info", "info-bg"]
REQUIRED_GROUPS = ["font", "font_size", "space", "radius", "shadow", "breakpoint"]
HEX = re.compile(r"#(?:[0-9a-fA-F]{8}|[0-9a-fA-F]{6}|[0-9a-fA-F]{3})\b")
ALLOWED_HOSTS = ("fonts.googleapis.com", "fonts.gstatic.com")


def ui_dir(args) -> Path:
    root = Path(args.project).resolve()
    if not (root / "01-sitemap.json").exists():
        sys.exit(f"error: {root} is not a spec folder (no 01-sitemap.json)")
    return root / "ui"


def cmd_init(args) -> None:
    ui = ui_dir(args)
    for sub in ("screens", "print", "archetypes", "kit"):
        (ui / sub).mkdir(parents=True, exist_ok=True)
    for f in ("proto.css", "proto.js"):
        shutil.copy2(KIT / f, ui / "kit" / f)
    approvals = ui / "approvals.md"
    if not approvals.exists():
        approvals.write_text(
            "# موافقات الواجهات\n\nنقاط موافقة إلزامية. لا تُعمَّم أي مرحلة قبل تسجيل موافقة المستخدم هنا (التاريخ + ما وافق عليه + ملاحظاته).\n\n"
            "| النقطة | الحالة | التاريخ | الملاحظات |\n|---|---|---|---|\n"
            "| 1. نظام التصميم (tokens + المكونات) | ⬜ بانتظار المستخدم | | |\n"
            "| 2. أنماط الشاشات | ⬜ بانتظار المستخدم | | |\n"
            "| 3. أول وحدة كاملة | ⬜ بانتظار المستخدم | | |\n", encoding="utf-8")
    if (ui / "tokens.json").exists():
        write_tokens_css(ui)
    print(json.dumps({"ui": str(ui), "kit": sorted(p.name for p in (ui / "kit").iterdir())}, ensure_ascii=False))


def css_value(group: str, value) -> str:
    if isinstance(value, (int, float)) and group in ("font_size", "space", "radius", "breakpoint"):
        return f"{value}px"
    return str(value)


def write_tokens_css(ui: Path) -> list[str]:
    tokens = json.loads((ui / "tokens.json").read_text(encoding="utf-8"))
    problems = [f"color.{k} missing" for k in REQUIRED_COLORS if k not in tokens.get("color", {})]
    problems += [f"group {g} missing" for g in REQUIRED_GROUPS if not tokens.get(g)]
    if tokens.get("color_dark"):
        problems += [f"color_dark.{k} missing" for k in REQUIRED_COLORS if k not in tokens["color_dark"]]
    if not tokens.get("contrast_pairs"):
        problems.append("contrast_pairs missing (list of [fg, bg, min_ratio])")
    prefix = {"font": "font", "font_size": "size", "space": "space", "radius": "radius", "shadow": "shadow",
              "breakpoint": "bp"}
    base = [f"  --color-{k}: {v};" for k, v in tokens.get("color", {}).items()]
    for group, pre in prefix.items():
        base += [f"  --{pre}-{k}: {css_value(group, v)};" for k, v in tokens.get(group, {}).items()]
    out = ["/* generated by ui_kit.py tokens from ui/tokens.json - do not edit by hand */"]
    fonts_url = (tokens.get("meta") or {}).get("google_fonts")
    if fonts_url:
        out.insert(0, f'@import url("{fonts_url}");')
    out += [":root {", *base, "}"]
    dark = tokens.get("color_dark")
    if dark:
        dark_vars = "\n".join(f"  --color-{k}: {v};" for k, v in dark.items())
        out += ["@media (prefers-color-scheme: dark) {", ':root:not([data-theme="light"]) {', dark_vars,
                "  color-scheme: dark;", "}", "}", ':root[data-theme="dark"] {', dark_vars, "  color-scheme: dark;", "}"]
    (ui / "kit" / "tokens.css").write_text("\n".join(out) + "\n", encoding="utf-8")
    return problems


def cmd_tokens(args) -> None:
    ui = ui_dir(args)
    (ui / "kit").mkdir(parents=True, exist_ok=True)
    problems = write_tokens_css(ui)
    print(json.dumps({"written": "ui/kit/tokens.css", "problems": problems}, ensure_ascii=False, indent=2))
    sys.exit(1 if problems else 0)


def lint_file(path: Path, ui: Path, rtl: bool) -> list[str]:
    text = path.read_text(encoding="utf-8", errors="replace")
    rel = path.relative_to(ui).as_posix()
    issues = []
    if rtl and not re.search(r'<html[^>]*\bdir="rtl"', text):
        issues.append("missing <html dir=\"rtl\">")
    if not re.search(r'<html[^>]*\blang="', text):
        issues.append("missing lang attribute")
    if "<title>" not in text:
        issues.append("missing <title>")
    if "kit/tokens.css" not in text or "kit/proto.css" not in text:
        issues.append("does not link kit/tokens.css and kit/proto.css")
    if "kit/proto.js" not in text and not rel.startswith("print/"):
        issues.append("does not load kit/proto.js")
    style_blocks = " ".join(re.findall(r"<style[^>]*>(.*?)</style>", text, re.S)) + " ".join(re.findall(r'style="([^"]*)"', text))
    if HEX.search(style_blocks):
        issues.append("literal colour in inline style - use tokens (var(--color-...))")
    for url in re.findall(r'(?:src|href)="(https?://[^"]+)"', text):
        if not any(h in url for h in ALLOWED_HOSTS):
            issues.append(f"external resource {url}")
    ids_with_label = set(re.findall(r'<label[^>]*\bfor="([^"]+)"', text))
    for m in re.finditer(r"<(input|select|textarea)\b([^>]*)>", text):
        attrs = m.group(2)
        if re.search(r'type="(hidden|submit|button)"', attrs):
            continue
        idm = re.search(r'\bid="([^"]+)"', attrs)
        labelled = (idm and idm.group(1) in ids_with_label) or "aria-label" in attrs or "aria-labelledby" in attrs
        if not labelled:
            # wrapped in <label>…</label>?
            before = text[:m.start()]
            if before.rfind("<label") <= before.rfind("</label>"):
                issues.append(f"unlabelled <{m.group(1)}> {attrs.strip()[:60]}")
    return [f"{rel}: {i}" for i in issues]


def cmd_lint(args) -> None:
    ui = ui_dir(args)
    tokens = json.loads((ui / "tokens.json").read_text(encoding="utf-8")) if (ui / "tokens.json").exists() else {}
    rtl = (tokens.get("meta") or {}).get("direction", "rtl") in ("rtl", "both")
    files = sorted(list((ui / "screens").rglob("*.html")) + list((ui / "archetypes").rglob("*.html"))
                   + list((ui / "print").rglob("*.html")))
    issues = [i for f in files for i in lint_file(f, ui, rtl)]
    print(json.dumps({"files": len(files), "issues": issues[:300], "count": len(issues)}, ensure_ascii=False, indent=2))
    sys.exit(1 if issues else 0)


def cmd_index(args) -> None:
    ui = ui_dir(args)
    root = ui.parent
    tokens = json.loads((ui / "tokens.json").read_text(encoding="utf-8")) if (ui / "tokens.json").exists() else {}
    meta = tokens.get("meta") or {}
    name = meta.get("product_name", "النظام الجديد")
    nav = json.loads((ui / "navigation.json").read_text(encoding="utf-8")) if (ui / "navigation.json").exists() else {"sections": []}
    sitemap = json.loads((root / "01-sitemap.json").read_text(encoding="utf-8"))
    screen_info = {}
    for m in sitemap.get("modules", []):
        for sec in m.get("sections", []):
            for sc in sec.get("screens", []):
                screen_info[sc["id"]] = (m["id"], sc.get("name", sc["id"]), sc.get("type", ""))
    e = html.escape

    def screen_link(sid: str) -> str:
        if sid not in screen_info:
            return f"<li>{e(sid)} <span class='muted'>(غير موجودة في الخريطة)</span></li>"
        mod, title, typ = screen_info[sid]
        proto = ui / "screens" / mod / f"{sid}.html"
        mp = ui / "screens" / mod / f"{sid}.map.md"
        link = f"<a href='screens/{e(mod)}/{e(sid)}.html'>{e(title)}</a>" if proto.exists() else f"{e(title)} <span class='badge danger'>بلا نموذج</span>"
        mlink = f" · <a class='muted' href='screens/{e(mod)}/{e(sid)}.map.md'>الربط</a>" if mp.exists() else ""
        return f"<li>{link} <span class='muted'>· {e(typ)}</span>{mlink}</li>"

    nav_html = []
    listed = set()
    for sec in nav.get("sections", []):
        items = []
        for item in sec.get("items", []):
            ids = item.get("screen_ids", [])
            listed.update(ids)
            items.append(f"<li><b>{e(item.get('label', ''))}</b><ul>{''.join(screen_link(s) for s in ids)}</ul></li>")
        nav_html.append(f"<section class='panel'><h3>{e(sec.get('label', ''))}</h3><ul class='tree'>{''.join(items)}</ul></section>")
    orphan = [sid for sid in screen_info if (ui / "screens" / screen_info[sid][0] / f"{sid}.html").exists() and sid not in listed]
    if orphan:
        nav_html.append(f"<section class='panel'><h3>شاشات خارج التنقل</h3><ul>{''.join(screen_link(s) for s in orphan)}</ul></section>")

    swatches = "".join(
        f"<div class='swatch'><span style='background:var(--color-{e(k)})'></span><code dir='ltr'>{e(k)}</code><small class='muted' dir='ltr'>{e(str(v))}</small></div>"
        for k, v in tokens.get("color", {}).items())
    arche = "".join(f"<li><a href='archetypes/{e(p.name)}'>{e(p.stem)}</a></li>" for p in sorted((ui / "archetypes").glob("*.html")))
    prints = "".join(f"<li><a href='print/{e(p.name)}'>{e(p.stem)}</a></li>" for p in sorted((ui / "print").glob("*.html")))
    comps = ""
    if (ui / "components.md").exists():
        heads = re.findall(r"^##\s+(.+)$", (ui / "components.md").read_text(encoding="utf-8"), re.M)
        comps = "".join(f"<li>{e(h)}</li>" for h in heads)
    coverage = ""
    if (ui / "coverage.md").exists():
        rows = re.findall(r"^\|\s*([^|]+?)\s*\|\s*([^|]+?)\s*\|$", (ui / "coverage.md").read_text(encoding="utf-8"), re.M)
        rows = [r for r in rows if r[0] not in ("المؤشر", "---")][:6]
        coverage = "".join(f"<tr><th>{e(a)}</th><td>{e(b)}</td></tr>" for a, b in rows)
    direction = "rtl" if meta.get("direction", "rtl") in ("rtl", "both") else "ltr"
    page = f"""<!doctype html>
<html lang="{e(meta.get('language', 'ar'))}" dir="{direction}">
<head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">
<title>{e(name)} — نظام الواجهات</title>
<link rel="stylesheet" href="kit/tokens.css"><link rel="stylesheet" href="kit/proto.css">
<style>
.swatches {{ display: grid; grid-template-columns: repeat(auto-fill, minmax(150px, 1fr)); gap: var(--space-3); }}
.swatch {{ display: flex; flex-direction: column; gap: 2px; font-size: var(--size-xs); }}
.swatch span {{ height: 44px; border-radius: var(--radius-sm); border: 1px solid var(--color-border); }}
.cols {{ display: grid; grid-template-columns: repeat(auto-fit, minmax(min(100%, 280px), 1fr)); gap: var(--space-4); }}
.tree, .tree ul {{ list-style: none; padding-inline-start: var(--space-3); margin: 0; display: flex; flex-direction: column; gap: 4px; }}
</style></head>
<body>
<header class="topbar"><strong class="brand">{e(name)}</strong><span class="muted">نظام الواجهات والنماذج التفاعلية</span>
<span class="grow"></span><button class="btn btn-ghost" type="button" data-theme-toggle>تبديل الوضع</button></header>
<main class="page">
<section class="panel"><h2>التغطية الوظيفية</h2><div class="table-wrap"><table class="data"><tbody>{coverage or '<tr><td>شغّل acs_tool.py uicheck</td></tr>'}</tbody></table></div>
<p class="muted">التفاصيل في <a href="coverage.md">coverage.md</a>.</p></section>
<section class="panel"><h2>الألوان</h2><div class="swatches">{swatches}</div></section>
<div class="cols">
<section class="panel"><h2>المكونات</h2><ul>{comps or '<li>ui/components.md غير موجود</li>'}</ul><p><a href="components.md">components.md</a></p></section>
<section class="panel"><h2>أنماط الشاشات</h2><ul>{arche or '<li>لا أنماط بعد</li>'}</ul></section>
<section class="panel"><h2>قوالب الطباعة</h2><ul>{prints or '<li>لا قوالب بعد</li>'}</ul></section>
</div>
<h2>الشاشات حسب التنقل الجديد</h2>
<div class="cols">{''.join(nav_html) or '<p>ui/navigation.json غير موجود</p>'}</div>
</main>
<script src="kit/proto.js"></script>
</body></html>
"""
    (ui / "index.html").write_text(page, encoding="utf-8")
    print(json.dumps({"written": "ui/index.html", "screens_in_nav": len(listed), "orphans": orphan}, ensure_ascii=False))


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = parser.add_subparsers(dest="cmd", required=True)
    for name, func in (("init", cmd_init), ("tokens", cmd_tokens), ("lint", cmd_lint), ("index", cmd_index)):
        p = sub.add_parser(name)
        p.add_argument("--project", default=".")
        p.set_defaults(func=func)
    args = parser.parse_args()
    args.func(args)


if __name__ == "__main__":
    main()
